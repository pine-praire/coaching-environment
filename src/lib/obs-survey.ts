// Опрос близких: вопросы, варианты ответов и индексы. Тексты перенесены из прототипа без изменений.
// Имя человека в git не хранится: {N} — именительный падеж, {A} — винительный, {D} — дательный.
// Формы имени задаются в /admin/blizkie и приходят со страницы только после верного пароля.

export interface SubjectNames {
  nom: string;
  acc: string;
  dat: string;
}

export function fillName(text: string, n: SubjectNames): string {
  return text.replace(/\{N\}/g, n.nom).replace(/\{A\}/g, n.acc).replace(/\{D\}/g, n.dat);
}

